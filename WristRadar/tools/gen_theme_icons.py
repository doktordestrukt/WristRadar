"""
Generates one round, launcher-safe app icon per built-in theme, plus the launcher aliases and
the ThemeIcons.kt lookup. Run from the WristRadar folder after adding or changing themes:

    python tools/gen_theme_icons.py

All artwork is generated (gradient backgrounds + the original glass radar foreground).
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAIN = os.path.join(ROOT, "app", "src", "main")
SETTINGS = os.path.join(MAIN, "java", "com", "wristradar", "data", "Settings.kt")
MANIFEST = os.path.join(MAIN, "AndroidManifest.xml")
DRAWABLE = os.path.join(MAIN, "res", "drawable")
MIPMAP = os.path.join(MAIN, "res", "mipmap-anydpi-v26")
KOTLIN = os.path.join(MAIN, "java", "com", "wristradar", "ui", "theme", "ThemeIcons.kt")

BEGIN = "<!-- THEME-ICONS-BEGIN (generated by tools/gen_theme_icons.py) -->"
END = "<!-- THEME-ICONS-END -->"


def argb_to_rgb(h):
    return "#" + h[-6:].upper()


def themes():
    src = open(SETTINGS, encoding="utf-8").read()
    block = src[src.index("val all = listOf("):src.index("const val CUSTOM_ID")]
    out = []
    for line in block.splitlines():
        line = line.strip()
        m = re.match(r'glass\("([a-z0-9_]+)",\s*"[^"]*",(.*)\),?$', line)
        if m:
            hexes = re.findall(r"0x[0-9A-Fa-f]{8}", m.group(2))
            out.append((m.group(1), [argb_to_rgb(h) for h in hexes[5:]]))   # bg stops after text,primary,secondary,out,conn
            continue
        m = re.match(r'ThemePreset\("([a-z0-9_]+)",\s*"[^"]*",(.*)\),?$', line)
        if m:
            body = m.group(2)
            if "listOf(" in body:
                grad = re.findall(r"0x[0-9A-Fa-f]{8}", body[body.index("listOf("):])
                out.append((m.group(1), [argb_to_rgb(h) for h in grad]))
            else:
                hexes = re.findall(r"0x[0-9A-Fa-f]{8}", body)
                primary, bg = argb_to_rgb(hexes[0]), argb_to_rgb(hexes[2])
                out.append((m.group(1), [primary, bg, bg]))
    return out


def gradient_xml(stops):
    stops = stops[:3] if len(stops) >= 2 else stops * 2
    center = f'\n        android:centerColor="{stops[1]}"' if len(stops) == 3 else ""
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/gen_theme_icons.py -->
<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
    <gradient android:angle="315" android:startColor="{stops[0]}"{center}
        android:endColor="{stops[-1]}" />
</shape>
'''


def adaptive_xml(tid):
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/gen_theme_icons.py -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_tbg_{tid}" />
    <foreground android:drawable="@drawable/ic_launcher_glass_fg" />
    <monochrome android:drawable="@drawable/ic_launcher_glass_fg" />
</adaptive-icon>
'''


def alias_xml(tid):
    return f'''        <activity-alias
            android:name=".ui.T_{tid}"
            android:targetActivity=".ui.MainActivity"
            android:icon="@mipmap/ic_t_{tid}"
            android:roundIcon="@mipmap/ic_t_{tid}"
            android:enabled="false"
            android:exported="true">
            <intent-filter>
                <action android:name="android.intent.action.MAIN" />
                <category android:name="android.intent.category.LAUNCHER" />
            </intent-filter>
        </activity-alias>
'''


def main():
    ts = themes()
    assert len(ts) >= 10, "theme parsing failed"
    for tid, stops in ts:
        open(os.path.join(DRAWABLE, f"ic_tbg_{tid}.xml"), "w", encoding="utf-8").write(gradient_xml(stops))
        open(os.path.join(MIPMAP, f"ic_t_{tid}.xml"), "w", encoding="utf-8").write(adaptive_xml(tid))

    man = open(MANIFEST, encoding="utf-8").read()
    aliases = "".join(alias_xml(t) for t, _ in ts)
    block = f"        {BEGIN}\n{aliases}        {END}\n"
    if BEGIN in man:
        a = man.index("        " + BEGIN)
        b = man.index(END) + len(END) + 1
        man = man[:a] + block + man[b:]
    else:
        i = man.index("    </application>")
        man = man[:i] + block + man[i:]
    open(MANIFEST, "w", encoding="utf-8").write(man)

    ids = ",\n        ".join(f'"{t}"' for t, _ in ts)
    open(KOTLIN, "w", encoding="utf-8").write(f'''package com.wristradar.ui.theme

/** Generated by tools/gen_theme_icons.py: themes that have their own launcher icon. */
object ThemeIcons {{
    val ids: Set<String> = setOf(
        {ids},
    )

    fun alias(themeId: String) = ".ui.T_$themeId"
}}
''')
    print(f"{len(ts)} theme icons generated")


if __name__ == "__main__":
    main()
